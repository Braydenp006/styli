// Command uiassets copies the design system into the web UI.
//
//	go run . ../../design ../../core/internal/web/ui/static
//
// It writes css/tokens.css (from design/tokens.json; light values by default,
// dark ones under prefers-color-scheme), css/components.css (a copy of
// design/components/styli.css) and the two logos. design/ is not part of the
// repository, so the output is committed and this only needs to run when the
// design changes.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type tokens struct {
	Color struct {
		Tokens []struct {
			Name  string `json:"name"`
			Value struct{ Light, Dark string }
		} `json:"tokens"`
	} `json:"color"`
	Type struct {
		Families map[string]string `json:"families"`
	} `json:"type"`
	Spacing struct {
		Tokens []nameValue `json:"tokens"`
	} `json:"spacing"`
	Radius struct {
		Tokens []nameValue `json:"tokens"`
	} `json:"radius"`
	Shadow struct {
		Tokens []struct {
			Name  string `json:"name"`
			Value struct{ Light, Dark string }
		} `json:"tokens"`
	} `json:"shadow"`
}

type nameValue struct{ Name, Value string }

const header = "/* Generated by `make ui-assets` from design/. Do not edit by hand. */\n"

// css builds tokens.css. Values come from a file we trust, but a stray ; or {
// would still break the whole stylesheet silently, so refuse them.
func css(t tokens) (string, error) {
	var light, dark strings.Builder
	add := func(b *strings.Builder, name, value string) error {
		if strings.ContainsAny(value, ";{}") || strings.ContainsAny(name, " ;{}:") || name == "" || value == "" {
			return fmt.Errorf("bad token %q: %q", name, value)
		}
		fmt.Fprintf(b, "  --%s: %s;\n", name, value)
		return nil
	}
	for _, c := range t.Color.Tokens {
		if err := add(&light, c.Name, c.Value.Light); err != nil {
			return "", err
		}
		if err := add(&dark, c.Name, c.Value.Dark); err != nil {
			return "", err
		}
	}
	for _, s := range t.Shadow.Tokens {
		if err := add(&light, s.Name, s.Value.Light); err != nil {
			return "", err
		}
		if err := add(&dark, s.Name, s.Value.Dark); err != nil {
			return "", err
		}
	}
	// The design names the families display, sans and mono.
	for _, k := range []string{"display", "sans", "mono"} {
		v, ok := t.Type.Families[k]
		if !ok {
			return "", fmt.Errorf("tokens.json has no %q font family", k)
		}
		if err := add(&light, "font-"+k, v); err != nil {
			return "", err
		}
	}
	for _, list := range [][]nameValue{t.Spacing.Tokens, t.Radius.Tokens} {
		for _, n := range list {
			if err := add(&light, n.Name, n.Value); err != nil {
				return "", err
			}
		}
	}
	return header + ":root {\n  color-scheme: light dark;\n" + light.String() + "}\n\n" +
		"@media (prefers-color-scheme: dark) {\n  :root {\n" + indent(dark.String()) + "  }\n}\n", nil
}

func indent(s string) string {
	return "  " + strings.ReplaceAll(strings.TrimSuffix(s, "\n"), "\n", "\n  ") + "\n"
}

func run(designDir, outDir string) error {
	b, err := os.ReadFile(filepath.Join(designDir, "tokens.json"))
	if err != nil {
		return err
	}
	var t tokens
	if err := json.Unmarshal(b, &t); err != nil {
		return fmt.Errorf("tokens.json: %w", err)
	}
	tokensCSS, err := css(t)
	if err != nil {
		return err
	}
	comps, err := os.ReadFile(filepath.Join(designDir, "components", "styli.css"))
	if err != nil {
		return err
	}
	files := map[string][]byte{
		"css/tokens.css":     []byte(tokensCSS),
		"css/components.css": append([]byte(header), comps...),
	}
	for _, logo := range []string{"styli-mark-light-bg.svg", "styli-mark-dark-bg.svg"} {
		if files["img/"+logo], err = os.ReadFile(filepath.Join(designDir, "logos", logo)); err != nil {
			return err
		}
	}
	for name, data := range files {
		dst := filepath.Join(outDir, name)
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(dst, data, 0o644); err != nil {
			return err
		}
		fmt.Println("wrote", dst)
	}
	return nil
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: uiassets DESIGN_DIR OUT_DIR")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, "uiassets:", err)
		os.Exit(1)
	}
}
